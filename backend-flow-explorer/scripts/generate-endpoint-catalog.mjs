import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const contractUrl = new URL("../../contracts/openapi.yaml", import.meta.url);
const outputUrl = new URL("../app/generated-endpoints.ts", import.meta.url);

const sourceByTag = {
  health: "backend/app/api/health.py",
  auth: "backend/app/api/v1/auth.py",
  collections: "backend/app/api/v1/collections.py",
  documents: "backend/app/api/v1/documents.py",
  artifacts: "backend/app/api/v1/artifacts.py",
  chat: "backend/app/api/v1/chat.py",
  models: "backend/app/api/v1/models.py",
  search: "backend/app/api/v1/search.py",
  audit: "backend/app/api/v1/audit.py",
  admin: "backend/app/api/v1/admin.py",
  sources: "backend/app/api/v1/sources.py",
  preferences: "backend/app/api/v1/preferences.py",
  user: "backend/app/api/v1/user.py",
  "saved-searches": "backend/app/api/v1/saved_searches.py",
  "mcp-servers": "backend/app/api/v1/mcp_servers.py",
  assistants: "backend/app/api/v1/assistants.py",
  "code-runs": "backend/app/api/v1/code_runs.py",
  schedules: "backend/app/api/v1/schedules.py",
  runs: "backend/app/api/v1/runs.py",
  "run-deliveries": "backend/app/api/v1/run_deliveries.py",
};

const sourceOverrides = {
  suggestSearch: "backend/app/api/v1/suggest.py",
  listRecentSearches: "backend/app/api/v1/suggest.py",
  clearRecentSearches: "backend/app/api/v1/suggest.py",
};

const handlerOverrides = {
  listChatSessions: "list_sessions",
  createChatSession: "create_session",
  getChatSession: "get_session",
  updateChatSession: "update_session",
  deleteChatSession: "delete_session",
  getChatSessionUsage: "get_session_usage",
};

const publicOperations = new Set(["getHealth", "getReadiness", "login", "refresh"]);
const methods = new Set(["get", "post", "put", "patch", "delete"]);

function snakeCase(value) {
  return value.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
}

function titleCase(value) {
  return value.replaceAll("-", " ").replace(/\b\w/g, (letter) => letter.toUpperCase());
}

const yaml = await readFile(contractUrl, "utf8");
const lines = yaml.split(/\r?\n/);
const endpoints = [];
let path = "";

for (let index = 0; index < lines.length; index += 1) {
  const pathMatch = lines[index].match(/^  (\/[^:]+):\s*$/);
  if (pathMatch) {
    path = pathMatch[1];
    continue;
  }

  const methodMatch = lines[index].match(/^    ([a-z]+):\s*$/);
  if (!path || !methodMatch || !methods.has(methodMatch[1])) continue;

  const method = methodMatch[1].toUpperCase();
  let operationId = "";
  let summary = "";
  let tag = "";
  for (let cursor = index + 1; cursor < lines.length; cursor += 1) {
    if (/^    [a-z]+:\s*$/.test(lines[cursor]) || /^  \/[^:]+:\s*$/.test(lines[cursor])) break;
    operationId ||= lines[cursor].match(/^      operationId:\s*(.+)$/)?.[1]?.trim() ?? "";
    summary ||= lines[cursor].match(/^      summary:\s*(.+)$/)?.[1]?.trim() ?? "";
    tag ||= lines[cursor].match(/^      tags:\s*\[([^\]]+)\]/)?.[1]?.trim() ?? "";
  }

  if (!operationId || !tag) continue;
  const runtimePath = tag === "health" ? path : `/api/v1${path}`;
  endpoints.push({
    id: `http-${method.toLowerCase()}-${runtimePath.replace(/[^a-zA-Z0-9]+/g, "-").replace(/^-|-$/g, "")}`,
    method,
    path: runtimePath,
    operationId,
    tag,
    domain: titleCase(tag),
    summary: summary.replace(/^['"]|['"]$/g, ""),
    transport: "HTTP",
    source: sourceOverrides[operationId] ?? sourceByTag[tag],
    handler: handlerOverrides[operationId] ?? snakeCase(operationId),
    auth: publicOperations.has(operationId) ? "Public" : "Bearer token",
  });
}

endpoints.push(
  {
    id: "ws-health",
    method: "WS",
    path: "/ws/health",
    operationId: "health_websocket",
    tag: "realtime",
    domain: "Realtime",
    summary: "Keepalive probe over a WebSocket connection.",
    transport: "WebSocket",
    source: "backend/app/realtime/health_ws.py",
    handler: "health_websocket",
    auth: "Public",
  },
  {
    id: "ws-chat-stream-id",
    method: "WS",
    path: "/ws/chat/{stream_id}",
    operationId: "chat_websocket",
    tag: "realtime",
    domain: "Realtime",
    summary: "Deliver owned chat-stream events to the authenticated browser.",
    transport: "WebSocket",
    source: "backend/app/realtime/chat_ws.py",
    handler: "chat_websocket",
    auth: "Query token + stream ownership",
  },
);

if (endpoints.length !== 114) {
  throw new Error(`Expected 114 endpoints; found ${endpoints.length}`);
}

const output = `// Generated by scripts/generate-endpoint-catalog.mjs from contracts/openapi.yaml.\n// Do not edit by hand.\n\nexport type EndpointDefinition = {\n  id: string;\n  method: string;\n  path: string;\n  operationId: string;\n  tag: string;\n  domain: string;\n  summary: string;\n  transport: "HTTP" | "WebSocket";\n  source: string;\n  handler: string;\n  auth: string;\n};\n\nexport const endpointCatalog: EndpointDefinition[] = ${JSON.stringify(endpoints, null, 2).replace(/"([^"\\]+)":/g, "$1:")};\n`;

await writeFile(outputUrl, output.replace('  transport: "HTTP" | "WebSocket";', '  transport:"HTTP" | "WebSocket";'), "utf8");
console.log(`Wrote ${endpoints.length} endpoints to ${fileURLToPath(outputUrl)}`);
